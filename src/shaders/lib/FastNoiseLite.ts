/**
 * Structure containing the entire noise system state.
 * Create using fnlCreateState() to ensure defaults are set.
 */
export interface FNLState {
	/** Seed used for all noise types. Default: 1337 */
	seed: number

	/** The frequency for all noise types. Default: 0.01 */
	frequency: number

	/** The noise algorithm to be used by GetNoise(). Default: FNL_NOISE_OPENSIMPLEX2 */
	noise_type: FNLNoiseType

	/** Sets noise rotation type for 3D. Default: FNL_ROTATION_NONE */
	rotation_type_3d: FNLRotationType3D

	/**
	 * The method used for combining octaves for all fractal noise types.
	 * FNL_FRACTAL_DOMAIN_WARP_* only affects fnlDomainWarp*
	 * Default: FNL_FRACTAL_NONE
	 */
	fractal_type: FNLFractalType

	/** The octave count for all fractal noise types. Default: 3 */
	octaves: number

	/** The octave lacunarity for all fractal noise types. Default: 2.0 */
	lacunarity: number

	/** The octave gain for all fractal noise types. Default: 0.5 */
	gain: number

	/** The octave weighting for all non-Domain Warp fractal types. Default: 0.0 */
	weighted_strength: number

	/** The strength of the fractal ping pong effect. Default: 2.0 */
	ping_pong_strength: number

	/** The distance function used in cellular noise calculations. Default: FNL_CELLULAR_DISTANCE_EUCLIDEANSQ */
	cellular_distance_func: FNLCellularDistanceFunc

	/** The cellular return type from cellular noise calculations. Default: FNL_CELLULAR_RETURN_TYPE_DISTANCE */
	cellular_return_type: FNLCellularReturnType

	/**
	 * The maximum distance a cellular point can move from its grid position.
	 * Default: 1.0
	 * @note Setting this higher than 1 will cause artifacts.
	 */
	cellular_jitter_mod: number

	/** The warp algorithm when using fnlDomainWarp*. Default: FNL_DOMAIN_WARP_OPENSIMPLEX2 */
	domain_warp_type: FNLDomainWarpType

	/** The maximum warp distance from original position when using fnlDomainWarp*. Default: 1.0 */
	domain_warp_amp: number
}

