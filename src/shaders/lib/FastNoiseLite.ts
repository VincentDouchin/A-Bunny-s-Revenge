/**
 * Cubic (Catmull-Rom style) interpolation across 4 control points a, b, c, d
 * p = (d - c) - (a - b)
 * t³p + t²((a-b) - p) + t(c-a) + b
 */
export const _fnlCubicLerp = /* #__PURE__ */ Fn<[Node<'float'>, Node<'float'>, Node<'float'>, Node<'float'>, Node<'float'>], Node<'float'>>(([a, b, c, d, t]) => {
	const p = d.sub(c).sub(a.sub(b))
	return t
		.mul(t)
		.mul(t)
		.mul(p)
		.add(t.mul(t).mul(a.sub(b).sub(p)))
		.add(t.mul(c.sub(a)))
		.add(b)
})

/**
 * Triangle-wave ping-pong: maps t into a 0→1→0 sawtooth
 * Equivalent to: t = t mod 2; return t < 1 ? t : 2 - t
 */
export const _fnlPingPong = /* #__PURE__ */ Fn<[Node<'float'>], Node<'float'>>(([t_in]) => {
	const t = float(t_in).toVar()
	// t -= float(int(t * 0.5)) * 2  →  equivalent to fmod(t, 2)
	t.subAssign(int(t.mul(0.5)).toFloat().mul(2))
	return select(lessThan(t, float(1)), t, float(2).sub(t))
})

/**
 * Pre-computes the normalization factor for fractal noise so the output
 * stays in [-1, 1] regardless of octave count.
 * Computed on the CPU from JS state values — returns a TSL float node.
 */
export function _fnlCalculateFractalBounding(state: FNLState) {
	const gain = Math.abs(state.gain)
	let amp = gain
	let ampFractal = 1.0
	for (let i = 1; i < state.octaves; i++) {
		ampFractal += amp
		amp *= gain
	}
	return 1.0 / ampFractal
}

